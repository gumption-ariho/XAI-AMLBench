VERSION = "v2.1  (repairs folders that Docker created in place of config files)"
MARK_FILE, MARK_END, PAYLOAD = "@@@@FILE: ", "@@@@END", "#==== PAYLOAD BELOW ===="
BACKUP = "_old_backup"
PORTS = {80: "Traefik (web + /api)", 3000: "frontend (direct)", 7474: "Neo4j Browser", 7687: "Neo4j Bolt",
         8080: "immudb console", 8081: "Traefik dashboard", 29092: "Kafka (host access)"}


def read_payload():
    text = Path(__file__).read_text(encoding="utf-8")
    body = text.split(PAYLOAD + "\n", 1)[1]
    files, path, buf = {}, None, []
    for raw in body.split("\n"):
        if not raw.startswith("#|"):
            continue
        line = raw[2:]
        if line.startswith(MARK_FILE):
            path, buf = line[len(MARK_FILE):].strip(), []
        elif line == MARK_END and path:
            files[path] = "\n".join(buf) + "\n"
            path = None
        elif path is not None:
            buf.append(line)
    return files


def find_target(args):
    if args:
        return Path(args[0]).expanduser()
    cwd = Path.cwd()
    if any((cwd / m).exists() for m in ("backend", "frontend", "docker-compose.yml")):
        return cwd
    return cwd / "xai-amlbench"


def make_env(example_text):
    alphabet = string.ascii_letters + string.digits       # no symbols: safe inside URLs and shell commands
    out = []
    for line in example_text.splitlines():
        if line.startswith("#") and "change_me" in line:      # template instruction, no longer true
            out.append("# Generated by setup_backend_v2.py: random passwords were filled in. Keep this file private.")
            continue
        m = re.match(r"^([A-Z0-9_]+)=change_me\w*\s*$", line)
        out.append(f"{m.group(1)}={''.join(secrets.choice(alphabet) for _ in range(24))}" if m else line)
    return "\n".join(out) + "\n"


