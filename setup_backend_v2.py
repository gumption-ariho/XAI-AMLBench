def root_owned(target):
    """Project paths owned by root. Docker creates a missing bind-mount path as a root-owned FOLDER."""
    found = []
    if not hasattr(os, "getuid") or os.getuid() == 0:
        return found
    skip = {"node_modules", ".git", ".venv", ".next", "_old_backup", "_old_js_backup"}
    for dp, dn, fn in os.walk(target):
        keep = []
        for d in dn:
            if d in skip:
                continue
            try:
                if (Path(dp) / d).lstat().st_uid == 0:
                    found.append(Path(dp) / d)      # do not descend: everything below is root's too
                    continue
            except OSError:
                pass
            keep.append(d)
        dn[:] = keep
        for f in fn:
            try:
                if (Path(dp) / f).lstat().st_uid == 0:
                    found.append(Path(dp) / f)
            except OSError:
                pass
    return found


def clear_slot(dest, target, backup, dry, problems):
    """`dest` must become a regular file but is a FOLDER (Docker made it). Remove it, or move it aside."""
    rel = dest.relative_to(target)
    empty = not any(dest.iterdir())
    what = "empty, removing it" if empty else f"has content, moving it to {dest.name}.was_a_folder"
    print(f"  FIX      {rel} is a FOLDER, not a file (Docker creates one when a mounted file is missing) - {what}")
    if dry:
        return True
    try:
        if empty:
            dest.rmdir()
        else:
            dest.rename(dest.with_name(dest.name + ".was_a_folder"))
        return True
    except OSError as e:
        # One command fixes every root-owned path at once (also the parent folders), then this script can finish alone.
        problems.append(f"sudo chown -R \"$USER\":\"$USER\" '{target.resolve()}'")
        print(f"  BLOCKED  {rel}  ({e.strerror}; it is owned by root)")
        return False


def install(target, files, dry, make_dotenv):
    backup = target / BACKUP
    print(("DRY RUN - nothing will be changed\n" if dry else "") + f"Project folder: {target.resolve()}\n")
    created = replaced = same = nblocked = 0
    problems = []
    for rel, content in files.items():
        dest = target / rel
        try:
            if dest.is_dir() and not dest.is_symlink():
                if not clear_slot(dest, target, backup, dry, problems):
                    continue
                print(f"  create   {rel}")
                created += 1
            elif dest.exists():
                if dest.read_text(encoding="utf-8", errors="replace") == content:
                    same += 1
                    continue
                b = backup / rel
                if not b.exists():
                    print(f"  backup   {rel}  ->  {BACKUP}/{rel}")
                    if not dry:
                        b.parent.mkdir(parents=True, exist_ok=True)
                        shutil.copy2(dest, b)
                print(f"  replace  {rel}")
                replaced += 1
            else:
                print(f"  create   {rel}")
                created += 1
            if not dry:
                dest.parent.mkdir(parents=True, exist_ok=True)
                dest.write_text(content, encoding="utf-8", newline="\n")
        except OSError as e:
            created = max(created - 1, 0) if not dest.exists() else created
            problems.append(f"sudo chown -R \"$USER\":\"$USER\" '{target.resolve()}'")
            nblocked += 1
            if nblocked <= 3:
                print(f"  BLOCKED  {rel}  ({e.strerror or e})")
    if nblocked > 3:
        print(f"  ... and {nblocked - 3} more files blocked the same way (the folders are owned by root)")
    if not dry:
        for d in ("data", "models"):
            try:
                (target / d).mkdir(parents=True, exist_ok=True)
            except OSError:
                pass

    env = target / ".env"
    if make_dotenv and ".env.example" in files:
        if env.exists():
            print("  .env     already exists - left untouched")
        else:
            print("  .env     created with random passwords (keep it private; it is in .gitignore)")
            if not dry:
                try:
                    env.write_text(make_env(files[".env.example"]), encoding="utf-8")
                    env.chmod(0o600)
                except OSError as e:
                    problems.append(f"sudo chown -R \"$USER\":\"$USER\" '{target.resolve()}'")
                    print(f"  BLOCKED  .env  ({e.strerror or e})")
    print(f"\n{'Would write' if dry else 'Done'}: {created} created, {replaced} replaced, {same} already up to date.")

    owned = root_owned(target)
    if owned:
        shown = ", ".join(str(p.relative_to(target)) for p in owned[:6]) + (" ..." if len(owned) > 6 else "")
        print(f"\nNote: these are owned by root (Docker created them): {shown}")
        print(f"      To take them back:   sudo chown -R \"$USER\":\"$USER\" '{target.resolve()}'")
        if not problems:
            pass
    if problems:
        print("\nCould not finish everything. Run these command(s), then run this script again:")
        for cmd in dict.fromkeys(problems):
            print(f"    {cmd}")
    return len(problems)


# ------------------------------------------------------------------------------------- doctor
def run(cmd, timeout=20, cwd=None):
    try:
        r = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout, cwd=cwd)
        return r.returncode, (r.stdout + r.stderr).strip()
    except FileNotFoundError:
        return 127, "not found"
    except subprocess.TimeoutExpired:
        return 124, "timed out"
    except OSError as e:                      # e.g. PermissionError: the command exists but you may not run it
        return 126, e.strerror or str(e)


def doctor(target, files):
    res = []

    def add(status, name, detail=""):
        res.append(status)
        print(f"  [{status:<4}] {name}" + (f"  -  {detail}" if detail else ""))

    print(f"Checking: {target.resolve()}\n")
    v = sys.version_info
    add("OK" if v < (3, 13) else "WARN", f"Python {v.major}.{v.minor}.{v.micro}",
        "fine" if v < (3, 13) else "too new for PyTorch on your own machine; the Docker images use Python 3.10/3.11, so this only matters if you run torch outside Docker")

    # --- disk: writable? enough space?  (you hit a read-only disk and 24 GB of build cache earlier)
    probe = target if target.exists() else target.parent
    try:
        t = probe / ".doctor_write_test"
        t.write_text("ok")
        t.unlink()
        add("OK", "Folder is writable")
    except OSError as e:
        add("FAIL", "Folder is NOT writable", f"{e.strerror} - if this says 'Read-only file system', reboot / remount before continuing")
    free = shutil.disk_usage(probe).free / 1e9
    add("OK" if free >= 25 else "WARN" if free >= 8 else "FAIL", f"Free disk space: {free:.0f} GB",
        "" if free >= 25 else "Docker images (PyTorch/CUDA, Kafka, Neo4j ...) need about 10-25 GB; run 'docker system df' and 'docker builder prune' to reclaim cache")

    # --- docker
    code, out = run(["docker", "--version"])
    if code != 0:
        add("FAIL", "Docker is not installed / not on PATH", out)
        have_docker = False
    else:
        add("OK", out.splitlines()[0])
        have_docker = True
        code, out = run(["docker", "compose", "version"])
        add("OK" if code == 0 else "FAIL", "Docker Compose v2" if code == 0 else "'docker compose' plugin missing",
            out.splitlines()[0] if code == 0 else "install docker-compose-plugin")
        code, out = run(["docker", "info", "--format", "{{.ServerVersion}}"], timeout=25)
        if code == 0:
            add("OK", f"Docker daemon reachable (server {out.strip()})")
            code, out = run(["docker", "ps", "-a", "--filter", "status=restarting", "--format", "{{.Names}}"])
            stuck = out.split() if code == 0 else []
            if stuck:
                add("WARN", "Containers stuck in a restart loop", ", ".join(stuck) + "  -> docker compose down   (then fix the cause and start again)")
        else:
            add("FAIL", "Docker daemon not reachable", "start it (sudo systemctl start docker) or add your user to the docker group")
            have_docker = False

    # --- files + .env
    wrong = [p for p in files if (target / p).is_dir()]
    if wrong:
        add("FAIL", f"{len(wrong)} config path(s) are FOLDERS instead of files", ", ".join(wrong[:4]) +
            "  (Docker creates a folder when a mounted file is missing) -> run this script, it repairs them")
    missing = [p for p in files if not (target / p).is_file() and p not in wrong]
    add("OK" if not missing else "FAIL", "Project files present" if not missing else f"{len(missing)} project files missing",
        "" if not missing else ", ".join(missing[:4]) + (" ..." if len(missing) > 4 else "") + "  -> run this script without --doctor")
    env = target / ".env"
    if not env.exists():
        add("FAIL", ".env missing", "run this script (it creates one) or: cp .env.example .env")
        env_keys = {}
    else:
        env_keys = dict(re.findall(r"^([A-Z0-9_]+)=(.*)$", env.read_text(encoding="utf-8"), flags=re.M))
        placeholders = [k for k, val in env_keys.items() if val.startswith("change_me")]
        add("OK" if not placeholders else "FAIL", ".env passwords set" if not placeholders else "placeholders still in .env",
            "" if not placeholders else ", ".join(placeholders))
    compose = target / "docker-compose.yml"
    if compose.exists():
        used = re.findall(r"\$\{([A-Z0-9_]+)(:-[^}]*)?\}", compose.read_text(encoding="utf-8"))
        need = sorted({n for n, default in used if not default})
        absent = [n for n in need if n not in env_keys]
        if env.exists():
            add("OK" if not absent else "FAIL", "Every ${VARIABLE} in docker-compose.yml is defined in .env",
                "" if not absent else "missing: " + ", ".join(absent))
        if have_docker and env.exists():
            code, out = run(["docker", "compose", "config", "-q"], cwd=str(target), timeout=40)
            add("OK" if code == 0 else "FAIL", "docker compose config is valid", "" if code == 0 else out.splitlines()[-1][:160])

    owned = root_owned(target)
    add("OK" if not owned else "WARN", "Nothing in the project is owned by root" if not owned else "Some project paths are owned by root",
        "" if not owned else ", ".join(str(p.relative_to(target)) for p in owned[:6]) +
        f"  -> sudo chown -R \"$USER\":\"$USER\" '{target.resolve()}'")

    # --- ports
    busy = []
    for port, what in PORTS.items():
        try:
            with socket.create_connection(("127.0.0.1", port), timeout=0.4):
                busy.append(f"{port} ({what})")
        except OSError:
            pass
    add("OK" if not busy else "WARN", "Ports free" if not busy else "Ports already in use",
        "" if not busy else ", ".join(busy) + "  - fine if this stack is already running, otherwise stop the other program")

    # --- GPU for the LLM profile
    code, out = run(["nvidia-smi", "-L"])
    if code == 0:
        add("OK", "NVIDIA GPU found", out.splitlines()[0][:80])
    else:
        add("WARN", "No NVIDIA GPU detected", "the 'llm' profile needs one. Without it set LLM_BACKEND=template in .env and delete the deploy: block of xai-narrative-api")

    # --- data / model state
    add("OK" if (target / "data" / "transactions.csv").exists() else "INFO", "Synthetic data",
        "found" if (target / "data" / "transactions.csv").exists() else "not generated yet (step 3 below)")
    add("OK" if (target / "models" / "gnn_model.pt").exists() else "INFO", "Trained GNN model",
        "found" if (target / "models" / "gnn_model.pt").exists() else "not trained yet (step 3 below)")

    fails, warns = res.count("FAIL"), res.count("WARN")
    print(f"\nResult: {res.count('OK')} OK, {warns} warnings, {fails} failures")
    return 1 if fails else 0


