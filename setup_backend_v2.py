#!/usr/bin/env python3
"""
setup_backend_v2.py  -  installs the BACKEND side of XAI-AMLBench into your project folder.

"Backend" here means everything except frontend/:
    backend/  gnn_aml_core/  xai_explainer/  aml_synth/  node_agent/
    docker-compose.yml  .env.example  traefik/  prometheus/  grafana/  README.md  .gitignore  .dockerignore
(The frontend has its own installer: setup_frontend_v2.py.)

Run it from your project root (the folder that contains frontend/ and backend/):

    python3 SCRIPT --dry-run     # show what WOULD change, touch nothing
    python3 SCRIPT               # install (safe to run again)
    python3 SCRIPT --doctor      # check this computer: Docker, disk space, ports, .env, GPU ...

Safety
  * Files that differ from the new version are first copied to  _old_backup/  (the first original is kept).
    Nothing is ever deleted.
  * Your existing  .env  is never touched. If there is none, one is created from  .env.example  with
    random passwords (use --no-env to skip that).

Every project file is stored below the PAYLOAD line as comment lines starting with "#|",
between "@@@@FILE: <path>" and "@@@@END" markers, so you can read it here as well.
"""
